function paper3_extract_case_data
%PAPER3_EXTRACT_CASE_DATA Copy the Paper 3 case inputs into this folder.
% Reads the full recordings in saved_results/tests (moved here from the
% project) and the canonical FEM/lead/notch files once, and writes trimmed, renamed
% copies under saved_results/paper3_cases. Each recording copy stores one
% top-level result struct. Units: t [s], dd/dc/dm [mm], fm [N].
package = fileparts(fileparts(mfilename('fullpath')));
project = fileparts(package);
src = fullfile(project, 'saved_results');
tests = fullfile(package, 'saved_results', 'tests'); % Full recordings, moved here.
dst = fullfile(package, 'saved_results', 'paper3_cases');
if ~isfolder(dst), mkdir(dst); end

% Healthy identification: diagnostic gain 1, numerical substructure active.
trimCopy(fullfile(tests, '20261119', 'id_healthy_gain1_20261119_2009.mat'), ...
    [85 218], fullfile(dst, 'id_healthy_gain1_20261119_2009_t085_218s.mat'));
% Case 1: PID notch off, fixed diagnostic gain 3.5.
trimCopy(fullfile(tests, '20261119', 'case1_notch_off_unstable_gain3p5_20261119_2052.mat'), ...
    [], fullfile(dst, 'case1_notch_off_gain3p5_20261119_2052.mat'));
% Case 2: PID notch on, otherwise identical to Case 1.
trimCopy(fullfile(tests, '20261120', 'case2_notch_on_stable_gain3p5_20261120_1035.mat'), ...
    [], fullfile(dst, 'case2_notch_on_gain3p5_20261120_1035.mat'));
% Case 3: PID notch on and OSI adaptation on, otherwise identical to Case 2.
trimCopy(fullfile(tests, '20261120', 'case3_notch_on_osi_on_stable_gain3p5_20261120_1052.mat'), ...
    [], fullfile(dst, 'case3_notch_on_osi_on_gain3p5_20261120_1052.mat'));
% Stiff-range performance pair: intensity 0.075, notch off / on, OSI off.
trimCopy(fullfile(tests, '20261120', 'stiff_notch_off_stable_gain3p5_i0p075_20261120_1125.mat'), ...
    [], fullfile(dst, 'stiff_notch_off_gain3p5_i0p075_20261120_1125.mat'));
trimCopy(fullfile(tests, '20261120', 'stiff_notch_on_stable_gain3p5_i0p075_20261120_1142.mat'), ...
    [], fullfile(dst, 'stiff_notch_on_gain3p5_i0p075_20261120_1142.mat'));

copyfile(fullfile(src, 'fem', 'fem_sp3_1o_rotfix.mat'), ...
    fullfile(dst, 'fem_numerical_rotation_fixed_damping10.mat'));
copyfile(fullfile(src, 'phase_lead', 'pl_sp4_codesign.mat'), ...
    fullfile(dst, 'lead_numerical_sp4_bandstop28hz.mat'));
copyfile(fullfile(src, 'controller_notch', 'notch_sp4.mat'), ...
    fullfile(dst, 'notch_pid_35p3hz.mat'));
end

function trimCopy(file, window, target)
r = load(file, 'result'); r = r.result;
i = true(size(r.t));
if ~isempty(window), i = r.t >= window(1) & r.t <= window(2); end
result = struct('t', r.t(i), 'dd', r.dd(i), 'dc', r.dc(i), 'dm', r.dm(i), ...
    'fm', r.fm(i), 'diagnostic_gain', r.Results(i, 21), ...
    'dd_pause_enable_log', r.dd_pause_enable_log(i), 'auth', r.auth(i), ...
    'fs', r.fs, 'dt', r.dt, 'pid_values', r.pid_values, ...
    'notch', r.hs.notch, 'num_notch', r.hs.num_notch, ...
    'fem_name', r.hs.fem_name, 'structural_model', r.hs.structural_model, ...
    'phase_lead_name', r.phase_lead_name, ...
    'intensity_factor', r.hs.intensity_factor, ...
    'source_file', file, 'window_s', window);
save(target, 'result');
end
